ARROWS = {"->": "→", "<-": "←"}


def glyphs(text: str) -> list[str]:
    """Split text into displayable glyphs: upper-cases it, turns -> and <- into arrows,
    and drops anything the font doesn't have."""
    t = text.upper()
    for k, v in ARROWS.items():
        t = t.replace(k, v)
    return [c for c in t if c in GLYPHS]


def bulbs_on(ch: str) -> list[int]:
    """Indices (row * 5 + col) of the bulbs lit for a character."""
    rows = GLYPHS[ch.upper()]
    return [r * COLS + c for r, row in enumerate(rows) for c, px in enumerate(row) if px == "#"]


def _check() -> None:
    for ch, rows in GLYPHS.items():
        assert len(rows) == ROWS and all(len(r) == COLS for r in rows), ch
        assert set("".join(rows)) <= {"#", "."}, ch


if __name__ == "__main__":
    _check()
    letters = [c for c in GLYPHS if c != " "]
    for start in range(0, len(letters), 9):
        group = letters[start:start + 9]
        print("   ".join(f"  {c}  " for c in group))
        for r in range(ROWS):
            print("   ".join(GLYPHS[c][r].replace("#", "●").replace(".", "·") for c in group))
        print()
    counts = {c: len(bulbs_on(c)) for c in letters}
    print("bulbs lit per glyph:", " ".join(f"{c}:{n}" for c, n in counts.items()))
    print(f"max {max(counts.values())} ({max(counts, key=counts.get)}), min {min(counts.values())} ({min(counts, key=counts.get)})")
